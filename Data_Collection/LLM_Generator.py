import os
from pathlib import Path
import json
import time
from dotenv import load_dotenv
from google import genai
from google.genai import types
from backoff_utils import compute_backoff


class QuotaExhaustedError(Exception):
    """Raised only when every retry failed AND at least one of those
    failures was specifically a rate-limit/quota error"""
    pass

base_dir = Path(__file__).resolve().parent.parent
env_path = base_dir / '.env'
load_dotenv(dotenv_path=env_path, override=True)

# Ensure API Key is present
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")
if not GEMINI_API_KEY:
    raise ValueError("GEMINI_API_KEY is missing. Add it to your .env file.")

# Initialize the Google GenAI Client
client = genai.Client(api_key=GEMINI_API_KEY)
GEMINI_MODEL = os.getenv("GEMINI_MODEL")

def normalize_keys(data: dict) -> dict:
    """
    Defensive engineering: Never trust LLM output schema casing.
    Converts all keys to lowercase and strips whitespace.
    """
    if not isinstance(data, dict):
        return {}
    return {str(k).lower().strip(): v for k, v in data.items()}

